//! Uçtan uca: gerçek ikili, geçici kök (`test-root`), sahte grub-mkconfig/mkinitcpio. Gerçek
//! `grub-mkfont` varsa onu kullanır (PF2 biçimi GRUB'un kendi aracından); yoksa test atlanır.
//!
//! Her senaryo uygula → doğrula → geri al → özgün hâl (bayt bayt) zincirini ya da hata yolunda
//! "hiçbir şey değişmedi" sonucunu denetler.

use std::os::unix::fs::PermissionsExt;
use std::path::{Path, PathBuf};
use std::process::Command;

use nuxut_boot_theme::BootColors;
use nuxut_system_helper::events::{Event, Outcome};

const FONT_CANDIDATES: &[(&str, &str)] = &[
    ("/usr/share/fonts/noto/NotoSans-Regular.ttf", "usr/share/fonts/noto/NotoSans-Regular.ttf"),
    ("/usr/share/fonts/TTF/DejaVuSans.ttf", "usr/share/fonts/TTF/DejaVuSans.ttf"),
];
const MONO_CANDIDATES: &[(&str, &str)] = &[
    ("/usr/share/fonts/noto/NotoSansMono-Regular.ttf", "usr/share/fonts/noto/NotoSansMono-Regular.ttf"),
    ("/usr/share/fonts/TTF/DejaVuSansMono.ttf", "usr/share/fonts/TTF/DejaVuSansMono.ttf"),
];

const GRUB_CFG: &str = "#\n# DO NOT EDIT THIS FILE\n#\n# It is automatically generated by grub-mkconfig using templates\n#\nmenuentry 'Arch Linux' {\n}\nmenuentry 'Arch Linux (fallback)' {\n}\n";
const LIMINE: &str = "timeout: 3\n\n/Arch Linux\n    protocol: linux\n    path: boot():/vmlinuz-linux\n";
const PLY_CONF: &str = "[Daemon]\nTheme=bgrt\nShowDelay=0\n";

struct Env {
    _t: tempfile::TempDir,
    root: PathBuf,
    bin: PathBuf,
}

fn write(p: &Path, s: impl AsRef<[u8]>) {
    std::fs::create_dir_all(p.parent().unwrap()).unwrap();
    std::fs::write(p, s).unwrap();
}

fn script(p: &Path, body: &str) {
    write(p, format!("#!/bin/sh\n{body}\n"));
    std::fs::set_permissions(p, std::fs::Permissions::from_mode(0o755)).unwrap();
}

fn setup() -> Option<Env> {
    let mkfont = Path::new("/usr/bin/grub-mkfont");
    let font = FONT_CANDIDATES.iter().find(|(src, _)| Path::new(src).exists())?;
    let mono = MONO_CANDIDATES.iter().find(|(src, _)| Path::new(src).exists())?;
    if !mkfont.exists() {
        return None;
    }
    let t = tempfile::tempdir().unwrap();
    let root = t.path().join("root");
    let bin = t.path().join("bin");
    std::fs::create_dir_all(&root).unwrap();
    std::fs::create_dir_all(&bin).unwrap();
    for (src, rel) in [font, mono] {
        let dst = root.join(rel);
        std::fs::create_dir_all(dst.parent().unwrap()).unwrap();
        std::fs::copy(src, dst).unwrap();
    }
    let r = |rel: &str| root.join(rel);
    write(&r("proc/cmdline"), "BOOT_IMAGE=/vmlinuz-linux root=UUID=x rw quiet splash\n");
    std::fs::create_dir_all(r("run")).unwrap();
    write(&r("usr/bin/grub-mkconfig"), "for dropin in ${sysconfdir}/default/grub.d/*.cfg ; do\n");
    write(&r("usr/bin/mkinitcpio"), "");
    write(&r("etc/mkinitcpio.conf"), "HOOKS=(base udev autodetect modconf kms keyboard plymouth block filesystems fsck)\n");
    write(&r("etc/mkinitcpio.d/linux.preset"), "PRESETS=('default')\ndefault_image=\"/boot/initramfs-linux.img\"\n");
    write(&r("boot/initramfs-linux.img"), "old-image");
    write(&r("usr/lib/plymouth/two-step.so"), "");
    write(&r("usr/share/plymouth/themes/spinner/keymap-render.png"), b"\x89PNG\r\n\x1a\nfake");
    write(&r("etc/plymouth/plymouthd.conf"), PLY_CONF);
    write(&r("etc/default/grub"), "GRUB_TIMEOUT=5\n");
    write(&r("boot/grub/grub.cfg"), GRUB_CFG);
    write(&r("boot/EFI/limine/limine.conf"), LIMINE);
    let mut efi = b"MZ++CONFIG_B2SUM_SIGNATURE++".to_vec();
    efi.extend(std::iter::repeat_n(b'0', 128));
    write(&r("boot/EFI/limine/BOOTX64.EFI"), efi);
    write(&r("fake/entries"), "2");
    // Tüm dizinler 0755 (tempdir 0700 açılır; doğrulama grup/diğer yazma bitine bakar).
    for e in walk(t.path()) {
        if e.is_dir() {
            std::fs::set_permissions(&e, std::fs::Permissions::from_mode(0o755)).unwrap();
        }
    }
    std::os::unix::fs::symlink(mkfont, bin.join("grub-mkfont")).unwrap();
    script(&bin.join("grub-script-check"), "exit 0");
    script(
        &bin.join("grub-mkconfig"),
        r#"R="$NUXUT_HELPER_TEST_ROOT"
[ "$1" = "-o" ] || exit 9
out="$2"
exit_code=$(cat "$R/fake/mkconfig_exit" 2>/dev/null || echo 0)
theme=""
for f in "$R"/etc/default/grub.d/*.cfg; do
  [ -f "$f" ] && . "$f" && theme="$GRUB_THEME"
done
{
  printf '#\n# DO NOT EDIT THIS FILE\n#\n# It is automatically generated by grub-mkconfig using templates\n#\n'
  if [ -n "$theme" ] && [ -f "$R$theme" ]; then echo "set theme=(\$root)$theme"; fi
  n=$(cat "$R/fake/entries")
  i=0; while [ $i -lt $n ]; do echo "menuentry 'e$i' {"; echo "}"; i=$((i+1)); done
} > "$out"
echo "Generating grub configuration file ..."
exit $exit_code"#,
    );
    script(
        &bin.join("mkinitcpio"),
        r#"R="$NUXUT_HELPER_TEST_ROOT"
[ "$1" = "-P" ] || exit 9
echo "==> Building image from preset: /etc/mkinitcpio.d/linux.preset: 'default'"
theme=$(sed -n 's/^Theme=//p' "$R/etc/plymouth/plymouthd.conf")
printf 'image-with-%s' "$theme" > "$R/boot/initramfs-linux.img"
exit $(cat "$R/fake/mkinitcpio_exit" 2>/dev/null || echo 0)"#,
    );
    Some(Env { _t: t, root, bin })
}

fn walk(p: &Path) -> Vec<PathBuf> {
    let mut out = vec![p.to_path_buf()];
    if p.is_dir() && !p.is_symlink() {
        for e in std::fs::read_dir(p).unwrap() {
            out.extend(walk(&e.unwrap().path()));
        }
    }
    out
}

/// Kökteki tüm dosyaların (yol, içerik) anlık görüntüsü.
fn snapshot(root: &Path) -> Vec<(String, Vec<u8>)> {
    let mut v: Vec<(String, Vec<u8>)> = walk(root)
        .into_iter()
        .filter(|p| p.is_file() && !p.starts_with(root.join("run")))
        .map(|p| (p.strip_prefix(root).unwrap().display().to_string(), std::fs::read(&p).unwrap()))
        .collect();
    v.sort();
    v
}

fn run(env: &Env, args: &[&str]) -> (bool, Vec<Event>) {
    let out = Command::new(env!("CARGO_BIN_EXE_nuxut-system-helper"))
        .args(args)
        .env("NUXUT_HELPER_TEST_ROOT", &env.root)
        .env("NUXUT_HELPER_TEST_BIN", &env.bin)
        .output()
        .unwrap();
    let events = String::from_utf8_lossy(&out.stdout)
        .lines()
        .map(|l| serde_json::from_str::<Event>(l).unwrap_or_else(|e| panic!("{e}: {l}")))
        .collect();
    assert!(out.status.code().is_some(), "sinyalle öldü (panik?)");
    (out.status.success(), events)
}

fn apply_args(targets: &str) -> Vec<String> {
    let mut v: Vec<String> = ["boot-theme", "apply", "--targets", targets, "--scale", "1", "--lang", "tr"].iter().map(|s| s.to_string()).collect();
    for c in BootColors::fallback().to_args() {
        v.push("--color".into());
        v.push(c);
    }
    v
}

fn apply(env: &Env, targets: &str) -> (bool, Vec<Event>) {
    let a = apply_args(targets);
    run(env, &a.iter().map(String::as_str).collect::<Vec<_>>())
}

fn outcome(events: &[Event], target: &str) -> Option<Outcome> {
    events.iter().find_map(|e| match e {
        Event::Target { target: t, outcome, .. } if t.name() == target => Some(*outcome),
        _ => None,
    })
}

fn read(env: &Env, rel: &str) -> String {
    String::from_utf8_lossy(&std::fs::read(env.root.join(rel)).unwrap_or_default()).into_owned()
}

#[test]
fn apply_then_revert_restores_everything() {
    let Some(env) = setup() else { return eprintln!("grub-mkfont ya da sistem fontu yok: atlandı") };
    let before = snapshot(&env.root);
    let (ok, ev) = apply(&env, "grub,limine,plymouth");
    assert!(ok, "{ev:#?}");
    for t in ["grub", "limine", "plymouth"] {
        assert_eq!(outcome(&ev, t), Some(Outcome::Applied), "{t}: {ev:#?}");
    }
    // GRUB: tema dizini (PF2 dahil), damla, temalı grub.cfg, yedek.
    assert!(env.root.join("boot/grub/themes/nuxut/theme.txt").exists());
    assert!(env.root.join("boot/grub/themes/nuxut/nuxut-16.pf2").exists());
    assert!(read(&env, "etc/default/grub.d/90-nuxut-theme.cfg").contains("GRUB_THEME=\"/boot/grub/themes/nuxut/theme.txt\""));
    assert!(read(&env, "boot/grub/grub.cfg").contains("set theme=($root)/boot/grub/themes/nuxut/theme.txt"));
    assert_eq!(read(&env, "etc/default/grub"), "GRUB_TIMEOUT=5\n", "kullanıcının dosyası değişmez");
    // Limine: blok başta, özgün satırlar korunmuş.
    let lim = read(&env, "boot/EFI/limine/limine.conf");
    assert!(lim.starts_with("# >>> nuxut-system-theme") && lim.ends_with(LIMINE), "{lim}");
    // Plymouth: tema, conf, initramfs yeniden kuruldu; işlem yedeği silindi.
    assert!(env.root.join("usr/share/plymouth/themes/nuxut/nuxut.plymouth").exists());
    assert!(env.root.join("usr/share/plymouth/themes/nuxut/keymap-render.png").exists());
    assert!(read(&env, "etc/plymouth/plymouthd.conf").contains("Theme=nuxut"));
    assert_eq!(read(&env, "boot/initramfs-linux.img"), "image-with-nuxut");
    let leftovers: Vec<_> = walk(&env.root.join("boot")).into_iter().filter(|p| p.to_string_lossy().contains("initramfs-linux.img.nuxut-")).collect();
    assert!(leftovers.is_empty(), "{leftovers:?}");
    assert!(env.root.join("var/lib/nuxut/system-theme/manifest.json").exists());

    // Yeniden uygulama: yeni kalıcı yedek yok, sonuç aynı.
    let (ok, ev) = apply(&env, "grub,limine,plymouth");
    assert!(ok, "{ev:#?}");
    let baks = walk(&env.root).into_iter().filter(|p| p.to_string_lossy().ends_with(".bak")).count();
    assert_eq!(baks, 3, "grub.cfg, limine.conf, plymouthd.conf özgün yedekleri");

    let (ok, ev) = run(&env, &["boot-theme", "revert"]);
    assert!(ok, "{ev:#?}");
    for t in ["grub", "limine", "plymouth"] {
        assert_eq!(outcome(&ev, t), Some(Outcome::Reverted), "{t}: {ev:#?}");
    }
    let mut after = snapshot(&env.root);
    // initramfs ve grub.cfg geri almada yeniden üretilir (eski kopya geri konmaz: çekirdek
    // güncellenmiş olabilir); içerikleri temasız hâl.
    for (p, b) in after.iter_mut() {
        if p == "boot/initramfs-linux.img" {
            assert_eq!(b.as_slice(), b"image-with-bgrt");
            *b = b"old-image".to_vec();
        }
        if p == "boot/grub/grub.cfg" {
            let s = String::from_utf8_lossy(b);
            assert!(!s.contains("themes/nuxut") && s.contains("menuentry"));
            *b = GRUB_CFG.replace("'Arch Linux'", "'e0'").replace("'Arch Linux (fallback)'", "'e1'").into_bytes();
        }
    }
    let mut before = before;
    for (p, b) in before.iter_mut() {
        if p == "boot/grub/grub.cfg" {
            *b = GRUB_CFG.replace("'Arch Linux'", "'e0'").replace("'Arch Linux (fallback)'", "'e1'").into_bytes();
        }
    }
    assert_eq!(after.iter().map(|x| &x.0).collect::<Vec<_>>(), before.iter().map(|x| &x.0).collect::<Vec<_>>(), "fazla/eksik dosya");
    assert_eq!(after, before);
}

